package org.example.answerBook.theFirstJavaProgram.task2;

/*
2. Метод subtract(int a, int b) возвращает разницу.
Подсказка: используй оператор -.
 */

public class TheDifferenceBetweenTwoNumbers {

	public static int subtract(int a, int b) {
		return a - b;
	}

	public static void main(String[] args) {
		System.out.println(subtract(2,4));
	}
}
