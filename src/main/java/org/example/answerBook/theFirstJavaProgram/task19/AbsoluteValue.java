package org.example.answerBook.theFirstJavaProgram.task19;

/*
19. Абсолютное значение
Метод absolute(int x) возвращает Math.abs(x).
 */

public class AbsoluteValue {

	public static double absolute(double x) {
		return Math.abs(x);
	}

	public static void main(String[] args) {
		System.out.println(absolute(122.511434212342));
	}
}
