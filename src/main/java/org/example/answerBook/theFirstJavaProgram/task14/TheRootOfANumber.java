package org.example.answerBook.theFirstJavaProgram.task14;

/*
14. Корень из числа
Метод squareRoot(double x) возвращает Math.sqrt(x).
 */

public class TheRootOfANumber {

	public static double squareRoot(int a) {
		return Math.sqrt(a);
	}

	public static void main(String[] args) {
		System.out.println(squareRoot(122));
	}
}
