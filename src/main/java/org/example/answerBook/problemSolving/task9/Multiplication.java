package org.example.answerBook.problemSolving.task9;

/*
Задача 9: Умножение

Описание:
 Метод multiply(int a, int b) возвращает произведение двух чисел. Ошибка в использовании оператора.
 */

public class Multiplication {

	public static int multiply(int a, int b) {
		return a * b;
	}

	public static void main(String[] args) {
		System.out.println(multiply(2, 5));
	}
}
